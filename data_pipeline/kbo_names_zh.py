def zh_name(hangul, foreign=False):
    if hangul in OVERRIDES:
        return OVERRIDES[hangul], False
    if foreign:
        return FOREIGN.get(hangul, hangul), True
    out = SURNAME.get(hangul[0], hangul[0]) + ''.join(GIVEN.get(c, c) for c in hangul[1:])
    return out, True
